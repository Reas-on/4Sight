import { expect, test } from "@playwright/test";
test.setTimeout(60000);

test("real persisted API/SSE → graph → results → retry, refresh and cancellation", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByLabel("AI Agent / Model", { exact: true })).toHaveValue("fixture:");
  await expect(page.getByRole("button", { name: "Run demonstration", exact: true })).toBeEnabled();
  await page.evaluate(() => { (window as unknown as { savedCanvas: Element | null }).savedCanvas = document.querySelector("canvas"); });
  const creation = page.waitForResponse((response) => response.url().endsWith("/api/v1/runs") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Run demonstration", exact: true }).click();
  expect((await creation).status()).toBe(202);
  await expect(page.locator(".app")).toHaveAttribute("data-run-id", /^[a-f0-9-]{36}$/);
  const first = await page.locator(".app").getAttribute("data-run-id");
  expect(first).toMatch(/^[a-f0-9-]{36}$/);
  await expect(page.getByTestId("graph-renderer")).toHaveAttribute("data-execution-node", /^N-0[145]$/);
  const results = page.getByRole("dialog", { name: "Simulation Results" });
  await expect(results).toBeVisible({ timeout: 15000 });
  await expect(results.locator(".results-outcome strong")).toHaveText("PASS");
  await expect(results).toContainText("N/A");
  await expect(results.getByTestId("results-step-count")).toHaveText("3");
  await expect(page.locator('.graph-label').filter({ hasText: "N-02" })).toHaveAttribute("data-status", "skipped");
  await expect(page.locator('.graph-label').filter({ hasText: "N-05" })).toHaveAttribute("data-status", "complete");
  await expect(results).toContainText("3 evaluated · 3 approved · 0 rejected");
  expect(await page.evaluate(() => (window as unknown as { savedCanvas: Element }).savedCanvas === document.querySelector("canvas"))).toBe(true);
  await page.getByRole("button", { name: "Close simulation results" }).click();
  await expect(results).toHaveCount(0);
  await page.locator("canvas").focus();
  await page.keyboard.press("Control+Space");
  await expect(results).toBeVisible();
  await page.keyboard.press("Control+Space");
  await expect(results).toHaveCount(0);
  await page.getByRole("button", { name: "Retry Demonstration", exact: true }).first().click();
  await expect(page.locator(".app")).not.toHaveAttribute("data-run-id", first!);
  await expect(page.locator(".app")).toHaveAttribute("data-simulation-status", "RUNNING");
  await expect(page.locator(".app")).toHaveAttribute("data-run-id", /^[a-f0-9-]{36}$/);
  const second = await page.locator(".app").getAttribute("data-run-id");
  await page.locator(".demo-controls .run-button").click();
  await expect(page.locator(".app")).toHaveAttribute("data-simulation-status", "PAUSED");
  await page.reload();
  await expect(page.locator(".app")).toHaveAttribute("data-run-id", second!);
  await expect(page.locator(".app")).toHaveAttribute("data-simulation-status", "PAUSED");
  await page.locator(".demo-controls .run-button").click();
  await expect(page.locator(".app")).toHaveAttribute("data-simulation-status", "RUNNING");
  await page.locator("canvas").focus();
  await page.keyboard.press("Control+Space");
  await expect(page.locator(".app")).toHaveAttribute("data-simulation-status", "CANCELLED");
  await expect(results).toBeVisible();
  await expect(results.locator(".results-outcome strong")).toHaveText("INCONCLUSIVE");
  await page.waitForTimeout(1000);
  await expect(page.locator(".app")).toHaveAttribute("data-simulation-status", "CANCELLED");
  await page.screenshot({ path: "/tmp/opencode/4sight-phase5-results.png" });
  expect(errors).toEqual([]);
});

test("test-only protected rejection is FAIL and unsupported context never executes a default scenario", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByLabel("AI Agent / Model", { exact: true })).toHaveValue("fixture:");
  await page.getByRole("button", { name: "Open Scenario Explorer" }).click();
  await page.getByRole("button", { name: /SSH Brute Force · Protected internal/ }).click();
  await page.getByRole("button", { name: "Use Scenario", exact: true }).click();
  await page.getByRole("button", { name: "Run demonstration", exact: true }).click();
  const results = page.getByRole("dialog", { name: "Simulation Results" });
  await expect(results).toBeVisible({ timeout: 15000 });
  await expect(results.locator(".results-outcome strong")).toHaveText("FAIL");
  await expect(results).toContainText("PROTECTED_SOURCE_BLOCK");
  await expect(page.locator('.graph-label').filter({ hasText: "N-04" })).toHaveAttribute("data-status", "rejected");
  await page.getByRole("button", { name: "Close simulation results" }).click();
  await page.getByLabel("Additional Context", { exact: true }).fill("unmapped context");
  await expect(page.getByRole("button", { name: "Retry Demonstration", exact: true }).first()).toBeDisabled();
  await expect(page.locator("#composition-status")).toContainText("unsupported");
});

test("backend unavailable is shown as a connection error without simulated success", async ({ page }) => {
  await page.route("**/api/v1/**", (route) => route.abort("connectionrefused"));
  await page.goto("/");
  await expect(page.locator("#composition-status")).toContainText("Backend connection error");
  await expect(page.locator(".demo-controls .run-button")).toBeDisabled();
  await expect(page.getByRole("dialog", { name: "Simulation Results" })).toHaveCount(0);
  await expect(page.locator(".app")).toHaveAttribute("data-simulation-status", "IDLE");
});
